import { api, cnpj, contactInput, createCustomer, createRoleSession, freshSeed, readyAdmin, unitInput } from './customers-hardening.helpers'

test('Customer and child text with HTML syntax stays inert in the UI', async ({ page }) => {
  const dialogs: string[] = []
  page.on('dialog', dialog => { dialogs.push(dialog.message()); void dialog.dismiss() })
  await readyAdmin(page)
  const payload = '<img data-e2e-xss src=x onerror="window.__e2eXss=1">'
  const customer = await createCustomer(page, freshSeed(), { legalName: `E2E ${payload}`, tradeName: `Trade ${payload}`, notes: `Notes ${payload}` })
  const contact = await api<{ version: string }>(page, 'POST', `/api/customers/${customer.id}/contacts`,
    { ...contactInput({ name: `Contact ${payload}` }), expectedVersion: customer.version })
  expect(contact.status).toBe(201)
  const unit = await api(page, 'POST', `/api/customers/${customer.id}/units`,
    { ...unitInput({ name: `Unit ${payload}` }), expectedVersion: contact.body.version })
  expect(unit.status).toBe(201)
  await page.goto(`/clientes/${customer.id}`)
  await expect(page.getByRole('heading', { name: `E2E ${payload}` })).toBeVisible()
  await expect(page.getByText(`Notes ${payload}`)).toBeVisible()
  await expect(page.getByText(`Contact ${payload}`).first()).toBeVisible()
  await expect(page.getByText(`Unit ${payload}`).first()).toBeVisible()
  expect(await page.evaluate(() => (window as Window & { __e2eXss?: number }).__e2eXss)).toBeUndefined()
  await expect(page.locator('[data-e2e-xss]')).toHaveCount(0)
  expect(dialogs).toEqual([])
})

